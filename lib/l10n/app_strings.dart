extension AppTr on BuildContext {
  /// Terjemahan sesuai bahasa aktif. Memakai Localizations sehingga widget
  /// otomatis dibangun ulang saat bahasa diganti.
  String tr(String key, [Map<String, String>? args]) =>
      AppStrings.get(Localizations.localeOf(this).languageCode, key, args);

  /// Nama kategori untuk ditampilkan (nilai di database tetap Indonesia).
  String catName(String category) =>
      category == 'Sistem Informasi' ? tr('cat_si') : category;
}